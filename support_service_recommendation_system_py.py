# Function to enhance description with type, industry, and barriers
def enhance_description(title, description, resource_type, potential_barriers):
    # Generate the prompt dynamically based on resource type
    prompt = f"Enhance the description for the following resource:\n\n"
    prompt += f"Title: {title}\n"
    prompt += f"Current description: {description if description else 'No description available.'}\n"
    prompt += f"Resource type: {resource_type}\n"
    prompt += f"Barriers: {', '.join(potential_barriers)}\n\n"
    prompt += (
    "Based on the title and current description, provide an expanded and detailed description for this resource. "
    "Include a brief overview of what the resource does, specifically mentioning its main purpose, services, or mission. "
    "Incorporate additional details that would be relevant to this resource. Be sure to include any industry-specific context, "
    "the particular needs or challenges it targets, and any other inferred information that would help a reader understand its benefits. "
    "Once enhanced, identify which of the following barriers this resource specifically addresses: "
    "{', '.join(potential_barriers)}. Be specific in linking the resource's services to the relevant barriers."
)


    try:
        # Call the OpenAI API to generate an enhanced description
        response = openai.ChatCompletion.create(
            model="gpt-3.5-turbo",
            messages=[{"role": "user", "content": prompt}],
        )
        enhanced_description = response['choices'][0]['message']['content']
        return enhanced_description
    except Exception as e:
        return str(e)

# Function to generate a unique resource_id based on enhanced description
def generate_resource_id(enhanced_description):
    # Use hashlib to create a unique hash of the enhanced description
    return hashlib.md5(enhanced_description.encode()).hexdigest()

