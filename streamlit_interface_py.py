def initialize_collection():
    # Read and process the CSV file
    file_path = '/Users/aashisrivastava/Documents/enhanced_resources.csv'
    df_enhanced = pd.read_csv(file_path, encoding='utf-8')

    # Convert embeddings from string to list
    df_enhanced['embedding'] = df_enhanced['embedding'].apply(lambda x: ast.literal_eval(x))

    # Delete collection if it exists
    try:
        client.delete_collection(collection_name)
    except:
        pass

    # Create new collection
    collection = client.create_collection(
        name=collection_name,
        metadata={"hnsw:space": "cosine"}
    )

    # Extract data
    resource_ids = df_enhanced['resource_id'].tolist()
    descriptions = df_enhanced['enhanced_description'].tolist()
    embeddings = df_enhanced['embedding'].tolist()

    # Process in smaller batches
    batch_size = 100
    for i in range(0, len(resource_ids), batch_size):
        end_idx = min(i + batch_size, len(resource_ids))
        collection.add(
            ids=[str(id) for id in resource_ids[i:end_idx]],
            documents=descriptions[i:end_idx],
            metadatas=[{"id": str(res_id)} for res_id in resource_ids[i:end_idx]],
            embeddings=embeddings[i:end_idx]
        )

    return collection

def generate_embedding(text):
    """Generate embedding using the updated OpenAI API"""
    response = openai.Embedding.create(
        model="text-embedding-ada-002",
        input=text
    )
    return response.data[0].embedding

