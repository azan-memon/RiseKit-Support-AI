# Function to extract concise query
def extract_concise_query(resume_text):
    prompt = f"""
    Analyze the following resume and summarize the candidate's work experience in a concise sentence.

    Resume: {resume_text}

    Focus on:
    - Relevant industries (e.g., Food Service, Warehousing, Logistics)
    - Avoid listing job titles or detailed skills
    - Conclude with a phrase like "is looking to upskill"

    Example: "A candidate with experience in [Industry 1], [Industry 2], and [Industry 3] is looking to upskill."
    """
    try:
        response = openai.ChatCompletion.create(
            model="gpt-3.5-turbo",
            messages=[{"role": "user", "content": prompt}],
        )
        query = response['choices'][0]['message']['content']
        return query.strip()
    except Exception as e:
        return f"Error: {e}"

